/**
 * Industry knowledge-base starter templates.
 *
 * Why these exist: a brand-new store's knowledge base is empty, and an
 * empty knowledge base means the confidence gate escalates literally every
 * question to a human (see modules/knowledge/retrieval.ts). A merchant who
 * connects Telegram in five minutes and then watches the AI answer nothing
 * concludes the product does not work — the failure looks like the AI, but
 * it is really a cold-start data problem. These templates give a new store
 * a plausible first knowledge base in one click, which the merchant then
 * edits to match reality.
 *
 * Deliberately pure data — no Prisma import, no DB calls, no `storeId`.
 * The caller decides which store the rows land in and who `created_by` is,
 * which is what keeps this file safe to import from the seed, from an API
 * route, and from tests alike. Attaching content to a store is always an
 * explicit, audited act by a human; see the note in prisma/seed.ts.
 *
 * Content notes: the copy is Saudi-market Arabic, and the restaurant
 * template is kept consistent with docs/15-saudi-market-and-restaurant-vertical.md
 * — Friday/Saturday weekend (§1), prayer-time gaps (§1), payment via a
 * link issued by a licensed system rather than in-chat payment (§3.4),
 * invoices coming from the POS as the single source of truth and never
 * generated by Maysoor (§2.2), and reservations handled inside the same
 * conversation (§7).
 */

export type IndustryTemplateKey = "restaurant" | "real_estate" | "salon" | "retail" | "fresh_seafood";

export interface IndustryKnowledgeEntry {
  /** Customer-phrased question — also stored in chunk metadata so the review UI can show it. */
  question: string;
  /** The answer the AI is allowed to ground on. Placeholders in [brackets] are meant to be edited. */
  answer: string;
  /** Coarse topic tag, mirrored into `knowledge_chunks.metadata` for filtering/analytics. */
  topic: "delivery" | "booking" | "pricing" | "hours" | "cancellation" | "general";
}

export interface IndustryTemplate {
  key: IndustryTemplateKey;
  /** Arabic label shown in the "choose your industry" step of onboarding. */
  name: string;
  /** Goes into `knowledge_sources.title`. */
  sourceTitle: string;
  /**
   * Goes into `knowledge_sources.type`. "faq" is an existing allowed value
   * (prisma/schema.prisma KnowledgeSource.type) — a new type value would
   * need every consumer of that column to learn about it, and these really
   * are FAQs, so there is nothing to gain from inventing one.
   */
  sourceType: "faq";
  entries: IndustryKnowledgeEntry[];
}

