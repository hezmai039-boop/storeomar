export function listIndustryTemplates(): IndustryTemplate[] {
  return Object.values(INDUSTRY_TEMPLATES);
}

/**
 * Looks a template up by key, for a key that arrives from a URL.
 *
 * The `hasOwn` guard is NOT defensive padding. `INDUSTRY_TEMPLATES` is an
 * ordinary object literal, so a plain index lookup walks the prototype chain:
 * `INDUSTRY_TEMPLATES["__proto__"]` returns an object and
 * `INDUSTRY_TEMPLATES["constructor"]` returns a function — both TRUTHY. The
 * apply route reads `template.entries.map(...)` right after its `if
 * (!template) 404`, so those keys sailed past the 404 and crashed on an
 * undefined `.entries` — a 500 that reads like an outage, from a URL any
 * authenticated manager can type.
 */
export function getIndustryTemplate(key: string): IndustryTemplate | undefined {
  if (!Object.hasOwn(INDUSTRY_TEMPLATES, key)) return undefined;
  return INDUSTRY_TEMPLATES[key as IndustryTemplateKey];
}

/**
 * One chunk = one Q&A pair, in the same "س: ... ج: ..." shape the learning
 * loop already writes into ai_suggested_knowledge (channels/routes.ts), so
 * retrieval scores template content and merchant-approved content
 * identically — the retriever tokenizes the question text along with the
 * answer, which is what lets a customer's phrasing match at all.
 */
export function templateChunkContent(entry: IndustryKnowledgeEntry): string {
  return `س: ${entry.question}\nج: ${entry.answer}`;
}

/** Body for `knowledge_sources.raw_text` — the whole template as one document. */
export function templateRawText(template: IndustryTemplate): string {
  return template.entries.map(templateChunkContent).join("\n\n");
}

/**
 * Metadata for `knowledge_chunks.metadata`. Tagging the origin is what
 * later makes it possible to tell "the merchant wrote this" from "we
 * seeded this and nobody ever edited it" — e.g. to stop nagging a store
 * whose knowledge base is technically non-empty but entirely placeholders.
 */
export function templateChunkMetadata(
  template: IndustryTemplate,
  entry: IndustryKnowledgeEntry
): { origin: "industry_template"; industry: IndustryTemplateKey; topic: string; question: string } {
  return {
    origin: "industry_template",
    industry: template.key,
    topic: entry.topic,
    question: entry.question,
  };
}
